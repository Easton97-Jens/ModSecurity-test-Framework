from __future__ import annotations
from modsecurity_test_framework.connector_context import connector_root, test_root, source_path, load_tool, load_source

import importlib.util
import sys
import unittest
from pathlib import Path


ROOT = connector_root()
SCRIPT = source_path('scripts/generate_repository_organization_inventory.py', root=ROOT)
INVENTORY = load_source(SCRIPT)

OPEN_BRACE = "$" + "{"


class RepositoryOrganizationInventoryTest(unittest.TestCase):
    def test_language_keeps_english_and_german_suffix_classification(self) -> None:
        self.assertEqual(INVENTORY.language("README.de.md"), "de")
        self.assertEqual(INVENTORY.language("README.md"), "en")
        self.assertEqual(INVENTORY.language("README.txt"), "n/a")

    def test_variable_regex_preserves_supported_and_rejected_forms(self) -> None:
        cases = {
            "$FOO": ["$FOO"],
            OPEN_BRACE + "FOO}": [OPEN_BRACE + "FOO}"],
            "$(FOO)": ["$(FOO)"],
            "VAR=": ["VAR="],
            "ABC =": ["ABC ="],
            "BUILD_MODE:=": ["BUILD_MODE:="],
            "FEATURE+=": ["FEATURE+="],
            "$FOO}": ["$FOO}"],
            f"{OPEN_BRACE}FOO": [f"{OPEN_BRACE}FOO"],
            f"{OPEN_BRACE}FOO)": [f"{OPEN_BRACE}FOO"],
            "$FOO=": ["$FOO"],
            "$foo": [],
            "$(FOO": [],
            "AB=": [],
            "lower=": [],
            "ABC-=": [],
            "$": [],
        }

        for text, expected in cases.items():
            with self.subTest(text=text):
                self.assertEqual(INVENTORY.variable_matches(text), expected)

    def test_reference_regex_preserves_known_reference_boundaries(self) -> None:
        cases = {
            "ci/checks/foo.py": ["ci/checks/foo.py"],
            "docs/a-b.md": ["docs/a-b.md"],
            "reports/a.b/c": ["reports/a.b/c"],
            "examples/demo.yml": ["examples/demo.yml"],
            "make check-docs": ["make check-docs"],
            "make\tquick-check": ["make\tquick-check"],
            "cix/foo": [],
            "myci/foo": [],
            "CI/foo": [],
            "ci/": [],
            "documentation/a": [],
            "make": [],
            "make /": [],
        }

        for text, expected in cases.items():
            with self.subTest(text=text):
                self.assertEqual(INVENTORY.REFERENCE_RE.findall(text), expected)

    def test_category_preserves_precedence_and_fallback(self) -> None:
        cases = (
            ("docs/security-inventory-fixture.md", "Generated by the inventory script", "generated"),
            ("docs/security-plan-inventory-fixture.md", "", "historical"),
            ("docs/security-inventory-fixture.md", "", "security"),
            ("reports/evidence-inventory-fixture.md", "", "evidence"),
            ("docs/test-inventory-build-fixture.md", "", "testing"),
            ("docs/build-inventory-architecture-fixture.md", "", "build-guide"),
            ("docs/common-inventory-roadmap-fixture.md", "", "architecture"),
            ("docs/roadmap-inventory-fixture.md", "", "roadmap"),
            ("docs/connectors/inventory-fixture.md", "", "connector-guide"),
            ("docs/apache-inventory-fixture.md", "", "connector-guide"),
            ("README-inventory-fixture.de.md", "", "entry-point"),
            ("docs/inventory-guide-fixture.md", "", "current-guide"),
        )

        for path, text, expected in cases:
            with self.subTest(path=path, text=text):
                self.assertEqual(INVENTORY.category(path, text), expected)

